package org.example.recommendation.service.rule;

import org.example.recommendation.model.RecommendationResponse.RecommendationItem;

import java.util.Optional;

/**
 * Интерфейс стратегии проверки правил рекомендации.
 * 
 * Согласно ТЗ: сервис получает id пользователя и по каждой рекомендации из таблицы
 * проверяет, подходит ли этот пользователь под правила этой рекомендации.
 * 
 * Паттерн Strategy: каждая реализация этого интерфейса — это отдельная стратегия
 * проверки одной конкретной рекомендации. Это позволяет:
 * - Легко добавлять новые рекомендации без изменения существующего кода
 * - Изолировать логику проверки каждой рекомендации
 * - Тестировать каждую стратегию отдельно
 * 
 * Реализации:
 * - RecommendationRuleSet1: правило 1 (DEBIT > 100000)
 * - RecommendationRuleSet2: правило 2 (DEBIT > 50000 ИЛИ DEPOSIT > 100000)
 * - RecommendationRuleSet3: правило 3 (DEBIT > 200000)
 */
public interface RecommendationRuleSet {
    
    /**
     * Проверяет, подходит ли пользователь под правила рекомендации.
     * 
     * Алгоритм:
     * 1. Загружает данные о транзакциях пользователя из БД
     * 2. Вычисляет необходимые агрегаты (суммы пополнений и т.д.)
     * 3. Проверяет условия правил (И/ИЛИ)
     * 4. Если пользователь подходит — возвращает продукт с описанием
     * 5. Если не подходит — возвращает пустой Optional
     * 
     * @param userId ID пользователя для проверки
     * @return RecommendationItem если пользователь подходит, пустой Optional иначе
     */
    Optional<RecommendationItem> check(String userId);

    /**
     * Возвращает ID продукта для этой рекомендации.
     * Используется для отладки и логирования.
     * 
     * @return ID продукта (например, "prod-001")
     */
    String getProductId();
}
